/**
 * Copies the migrations drizzle-kit wrote to `drizzle/` into
 * `electron/project/migrations.gen.ts`, so they are bundled into the main process instead of
 * read from disk at runtime. `bun run db:generate` runs this after drizzle-kit; the electron
 * tests fail when the two are out of step.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const migrationsDir = path.join(root, "drizzle");
export const generatedFile = path.join(root, "electron/project/migrations.gen.ts");

/** The generated module's source for the migrations in `dir`, oldest first. */
export function migrationsModule(dir: string): string {
  const folders = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(dir, entry.name, "migration.sql")))
    .map((entry) => entry.name)
    .toSorted();
  const migrations = folders.map((name) => {
    const text = fs.readFileSync(path.join(dir, name, "migration.sql"), "utf8");
    const statements = text
      .split("--> statement-breakpoint")
      .map((statement) => statement.trim())
      .filter(Boolean);
    return { name, statements };
  });
  return [
    "// Generated by scripts/bundle-migrations.ts from drizzle/. Don't edit; run `bun run db:generate`.",
    "",
    "/** The project format's migrations, oldest first. Format version N has the first N applied. */",
    `export const migrations: ReadonlyArray<{ readonly name: string; readonly statements: readonly string[] }> = ${JSON.stringify(migrations, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  fs.writeFileSync(generatedFile, migrationsModule(migrationsDir));
  console.log(`Wrote ${path.relative(root, generatedFile)}`);
}
